import sys,json,shutil,hashlib
from pathlib import Path
from PIL import Image,ImageDraw
root=Path(__file__).resolve().parents[1]
source=Path(sys.argv[1])
archive=root/'art-review/2026-11-13/recessed-eye/approved-preview.png'
if source.resolve()!=archive.resolve():shutil.copyfile(source,archive)
im=Image.open(archive).convert('RGBA').resize((256,216),Image.Resampling.NEAREST)
# Retain only the recessed mechanism and stone surround, not generated background bricks.
mask=Image.new('L',(256,216));draw=ImageDraw.Draw(mask)
