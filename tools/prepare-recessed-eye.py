for rect in [(117,24,139,51),(44,94,73,123),(186,94,212,123),(116,157,139,183)]:draw.rectangle(rect,fill=255)
im.putalpha(mask);im=im.crop((44,24,213,184))
asset=root/'dist/assets/secret/recessed-eye.png';im.save(asset)
# Lossless run-length encoding keeps a synchronous renderer with no image-load flash.
runs=[]
for r,g,b,a in im.getdata():
 value=(r<<24)|(g<<16)|(b<<8)|a
 if runs and value==runs[-1]:runs[-2]+=1
 else:runs.extend([1,value])
out='// Approved inset, nearest-neighbor at native corridor resolution. Generated by tools/prepare-recessed-eye.py.\n'
out+='export const EYE_WIDTH=169,EYE_HEIGHT=160;\nexport const EYE_UV=Object.freeze({x:34.6,y:39.111111111111114,width:59.15,height:47.407407407407405});\n'
out+='const runs='+json.dumps(runs,separators=(',',':'))+';\n'
out+='export const EYE_PIXELS=new Uint8ClampedArray(EYE_WIDTH*EYE_HEIGHT*4);let offset=0;for(let i=0;i<runs.length;i+=2){const color=runs[i+1];for(let n=0;n<runs[i];n++){EYE_PIXELS[offset++]=color>>>24;EYE_PIXELS[offset++]=color>>>16&255;EYE_PIXELS[offset++]=color>>>8&255;EYE_PIXELS[offset++]=color&255;}}\n'
(root/'dist/secret-eye-pixels.js').write_text(out)
(root/'art-review/2026-11-13/recessed-eye/asset-sha256.json').write_text(json.dumps({str(asset.relative_to(root)):hashlib.sha256(asset.read_bytes()).hexdigest(),str(archive.relative_to(root)):hashlib.sha256(archive.read_bytes()).hexdigest()},indent=2)+'\n')
print('Prepared approved inset:',im.size,'RLE bytes:',len(out))
