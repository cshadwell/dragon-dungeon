from PIL import Image
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'art-review/2026-10-25/doors/source.png').convert('RGBA')
out=root/'dist/assets/doors';out.mkdir(exist_ok=True)
# Isolate each supplied panel; only edge-connected near-white background is removed.
from collections import deque
records={}
for i,name in enumerate(['ogre','wizard','elf','dragon']):
 a=im.crop((round(i*im.width/4),0,round((i+1)*im.width/4),im.height));p=a.load();w,h=a.size;q=deque([(x,y) for x in range(w) for y in [0,h-1]]+[(x,y) for y in range(h) for x in [0,w-1]]);seen=set()
 while q:
  x,y=q.popleft()
  if (x,y) in seen or not(0<=x<w and 0<=y<h):continue
  seen.add((x,y));r,g,b,alpha=p[x,y]
  if min(r,g,b)<235:continue
  p[x,y]=(r,g,b,0);q.extend([(x-1,y),(x+1,y),(x,y-1),(x,y+1)])
 a=a.crop(a.getbbox());a=a.resize((round(a.width*112/a.height),112),Image.Resampling.NEAREST)
 tile=Image.new('RGBA',(128,128));tile.alpha_composite(a,((128-a.width)//2,16));tile.save(out/f'{name}.png')
 records[name]=list(tile.getdata())
(root/'dist/door-pixels.js').write_text('// Generated by tools/prepare-doors.py from supplied Doors.png. 128px wall grid.\nexport const DOOR_PIXELS='+json.dumps(records,separators=(',',':'))+';\n')
